#!/usr/bin/env node
// build-accent-model.js -- writes js/accent-model.js: the small learned
// pattern-choice table js/mora-segment.js uses (see its "learned pattern
// choice" comment). One diagonal Gaussian over the F0-ratio vector (cents
// step between adjacent mora slots, Ishi, Minematsu & Hirose 2001) per
// (mora count, pattern), with >= 10 training takes, from the SAME
// production slot values the app computes.
//
// Trained on exactly the configuration evaluated in
// docs/paper/2026-09-25-interspeech-plan.md: JSUT app-like + phrase
// samples from sentences BASIC5000_0001-4000 (the held-out 4001-5000 and
// all of UME-JRF were never seen). Regenerate after ANY change to
// js/mora-segment.js's front end (gate, delay, slotting, MORA_VALUE), since
// the features are its slot values.
//
// Usage: JSUT_LABEL_DIR=... node tools/build-accent-model.js
'use strict';
const fs = require('fs');
const path = require('path');
const H = require('./paper-harness.js');
const L = require('./paper-exp-learned-lib.js');

const D = H.load();
const model = L.trainGauss([].concat(D.jsutApp.train, D.jsutPhrase.train));
const VAR_FLOOR = 2500; // cents^2, same floor the evaluation used
const table = {};
let params = 0;
for (const [n, m] of [...model.entries()].sort((a, b) => a[0] - b[0])) {
  for (const [pat, g] of m) {
    if (g.n < 10) continue;
    const mu = g.s.map((x) => x / g.n);
    const va = g.q.map((x, i) => Math.max(VAR_FLOOR, x / g.n - mu[i] * mu[i]));
    (table[n] = table[n] || {})[pat] = { mu: mu.map((x) => Math.round(x * 10) / 10), v: va.map((x) => Math.round(x)) };
    params += 2 * mu.length;
  }
}
const src = `// accent-model.js -- GENERATED by tools/build-accent-model.js; do not edit.
// The learned pattern-choice table js/mora-segment.js uses: per mora count,
// per valid pitch pattern, the mean (mu) and variance (v) of each F0-ratio
// feature (cents step between adjacent mora slots). ${params} numbers, trained
// on JSUT sentences 1-4000 only. Static data, no runtime inference library.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.AccentModel = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  return ${JSON.stringify({ version: 1, params, models: table })};
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'accent-model.js'), src);
console.error(`js/accent-model.js written: ${params} numbers, ${Object.keys(table).length} mora counts`);
